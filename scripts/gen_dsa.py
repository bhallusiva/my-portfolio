"""Builds src/data/dsa.generated.ts from a local clone of github.com/bhallusiva/DSA.
Usage: python3 scripts/gen_dsa.py /path/to/DSA"""
import os, re, sys, json
root = sys.argv[1]
TOPICS = {
 "Backtracking": {37,39,40,46,51,78,79,90,131,216},
 "Binary search": {4,74,240,1011,1552,1870},
 "Greedy": {455,860,1029,1833,2410},
 "Recursion & DP": {50,62,70},
}
def topic(num, slug):
    for t, s in TOPICS.items():
        if num in s: return t
    if "bst" in slug.split("-") or any(k in slug for k in ("tree","path-sum","root-to-leaf","next-right-pointers","lowest-common-ancestor")): return "Trees & BST"
    if "list" in slug or "nodes" in slug or slug in ("add-two-numbers","add-two-numbers-ii","rotate-list"): return "Linked lists"
    if any(k in slug for k in ("palindrom","anagram","string","roman","common-prefix","parenthes","isomorphic")): return "Strings"
    return "Arrays & math"
probs=[]
for d in sorted(os.listdir(root)):
    m=re.match(r"(\d{4})-(.+)",d)
    if not m: continue
    num=int(m.group(1)); slug=m.group(2)
    r=open(f"{root}/{d}/README.md",errors="ignore").read()
    t=re.search(r"<h2><a href=\"([^\"]+)\">\d+\.\s*([^<]+)</a></h2><h3>(Easy|Medium|Hard)</h3>",r)
    assert t, d
    probs.append(dict(n=num,dir=d,title=t.group(2).strip(),lc=t.group(1),d=t.group(3),t=topic(num,slug)))
practice={}
for d in sorted(os.listdir(root)):
    p=f"{root}/{d}"
    if os.path.isdir(p) and not re.match(r"\d{4}-",d) and not d.startswith("."):
        files=sorted(f for f in os.listdir(p) if f.endswith(".java"))
        if files: practice[d]=files
out="// GENERATED by scripts/gen_dsa.py from github.com/bhallusiva/DSA - do not edit by hand.\n"
out+="export type Difficulty = 'Easy' | 'Medium' | 'Hard'\n"
out+="export interface DsaProblem { n: number; dir: string; title: string; lc: string; d: Difficulty; t: string }\n"
out+="export const dsaProblems: DsaProblem[] = "+json.dumps(probs,indent=0)+"\n"
out+="export const dsaPractice: Record<string, string[]> = "+json.dumps(practice,indent=0)+"\n"
open("src/data/dsa.generated.ts","w").write(out)
import collections
print(len(probs), collections.Counter(p['t'] for p in probs), collections.Counter(p['d'] for p in probs))
print({k:len(v) for k,v in practice.items()}, sum(len(v) for v in practice.values()))
